"""Numerical classification reuses source evidence only until fresh publication."""

from dataclasses import replace
from hashlib import sha256

import pytest
from fparser.two import Fortran2003 as F
from fparser.two.utils import walk

from compiler.driver.options import CompilerOptions
from compiler.frontend import source_effects
from compiler.frontend.summary_cache import SummaryCache
from compiler.ir import CompilationError
from compiler.offload import source_compute
from compiler.offload.config import OffloadConfig
from compiler.scopes import source

ENTRY = "local_classification::evaluate"
SOURCE = """module local_classification
implicit none
contains
subroutine evaluate(a,n)
real(8),intent(inout)::a(:)
integer,intent(in)::n
integer::i
do i=1,n
a(i)=sqrt(a(i)*a(i)+1.0_8)+cos(a(i))
enddo
end subroutine
end module
"""


@pytest.fixture
def subject(tmp_path, monkeypatch):
    monkeypatch.setattr(source_effects, "_DEFAULT_SUMMARY_CACHE", SummaryCache())
    path = tmp_path / "original.f90"
    path.write_text(SOURCE)
    facts = {"schema_version": 1, "participation": "serial",
             "sources": {str(path): sha256(path.read_bytes()).hexdigest()},
             "captures": {"argument::a": {"storage": "stable", "initialized": "whole",
                                          "escapes": False, "allocation_changes": False}}}
    builder = source.ScopeBuilder([path], ENTRY, facts=facts, options=CompilerOptions(),
                                  config=OffloadConfig(policy="sections"))
    return path, builder


def record_demands(monkeypatch, builder):
    original = builder.analysis.summarize
    summaries = []

    def summarize(procedure, *args, **kwargs):
        result = original(procedure, *args, **kwargs)
        if kwargs.get("_closure") is None:
            summaries.append(result)
        return result

    monkeypatch.setattr(builder.analysis, "summarize", summarize)
    return summaries


def test_one_classification_issues_one_summary_before_fresh_success_validation(subject, monkeypatch):
    _path, builder = subject
    summaries = record_demands(monkeypatch, builder)
    original_require = builder.analysis._require_original
    original_generate = source.generate_sources
    generation_complete = False
    validated = []

    def generate(*args, **kwargs):
        nonlocal generation_complete
        result = original_generate(*args, **kwargs)
        generation_complete = True
        return result

    def require(procedure, *, _syntax=None):
        result = original_require(procedure, _syntax=_syntax)
        validated.append((procedure, _syntax, generation_complete,
                          procedure in builder.generated, procedure in builder.numerical_ir))
        return result

    monkeypatch.setattr(source, "generate_sources", generate)
    monkeypatch.setattr(builder.analysis, "_require_original", require)
    generated = builder.numerical(ENTRY)
    assert generated is not None, builder.numerical_reasons
    assert len(summaries) == 1
    assert summaries[0]["procedure"] == ENTRY
    assert summaries[0]["summary_role"] == "source"
    assert any(procedure == ENTRY and syntax is not None and complete and not adopted and not lowered
               for procedure, syntax, complete, adopted, lowered in validated)
    assert builder.generated[ENTRY] is generated
    assert ENTRY in builder.numerical_ir


def test_generated_sources_equal_independently_fresh_dependent_demands(subject, monkeypatch):
    path, builder = subject
    reused = builder.numerical(ENTRY)
    assert reused is not None, builder.numerical_reasons
    fresh = source.ScopeBuilder([path], ENTRY, facts=builder.facts, options=builder.options, config=builder.config)
    demands = record_demands(monkeypatch, fresh)
    original_origins = fresh._check_numerical_capture_origins
    original_effects = fresh._native_effects
    original_participation = source_compute._native_participation

    # Exercise the previous independent-demand route through the same pure
    # implementations. This oracle retains every generated byte and report key.
    def origins(procedure, _issued_summary):
        return original_origins(procedure, fresh.analysis.summarize(procedure))

    def effects(procedure, mapping=None, active=(), *, allow_views=False, summary=None):
        return original_effects(procedure, mapping, active, allow_views=allow_views)

    def participation(analysis, procedure, _issued_completion):
        return original_participation(analysis, procedure, analysis.summarize(procedure)["native_completion"])

    monkeypatch.setattr(fresh, "_check_numerical_capture_origins", origins)
    monkeypatch.setattr(fresh, "_native_effects", effects)
    monkeypatch.setattr(source_compute, "_native_participation", participation)
    independently_checked = fresh.numerical(ENTRY)
    assert independently_checked is not None, fresh.numerical_reasons
    assert len(demands) == 4
    assert independently_checked.artifacts == reused.artifacts
    assert independently_checked.scoped == reused.scoped


@pytest.mark.parametrize("change", ["execution", "file", "contracts", "config", "options"])
def test_mid_classification_mutation_is_hard_and_cannot_adopt_generated_artifacts(subject, monkeypatch, change):
    path, builder = subject
    builder.analysis.contracts["unused_external"] = {"identity": "original"}
    assignment, = walk(builder.analysis.routines[ENTRY].execution, F.Assignment_Stmt)
    original_generate = source.generate_sources
    generated = []

    def generate(*args, **kwargs):
        result = original_generate(*args, **kwargs)
        generated.append(result)
        if change == "execution":
            assignment.items = (*assignment.items[:2], assignment.items[0])
        elif change == "file":
            path.write_text(SOURCE + "! source changed during classification\n")
        elif change == "contracts":
            builder.analysis.contracts["unused_external"]["identity"] = "changed"
        elif change == "config":
            builder.config = replace(builder.config, host_threads=builder.config.host_threads + 1)
        else:
            builder.options = replace(builder.options, opt_level=0)
        return result

    monkeypatch.setattr(source, "generate_sources", generate)
    with pytest.raises(CompilationError, match="changed|authority"):
        builder.numerical(ENTRY)
    assert len(generated) == 1
    assert generated[0].scoped
    assert ENTRY not in builder.generated
    assert ENTRY not in builder.numerical_ir
    assert ENTRY not in builder.numerical_reasons
    assert builder.outputs == {}


def test_standalone_helpers_stay_fresh_and_keep_private_projection_semantics(subject, monkeypatch):
    _path, builder = subject
    summaries = record_demands(monkeypatch, builder)
    builder.check_numerical_capture_origins(ENTRY)
    original_effects = builder.native_effects(ENTRY)
    assert source_compute.native_participation(builder.analysis, ENTRY) == "serial"
    assert len(summaries) == 3
    assert {summary["summary_role"] for summary in summaries} == {"source"}
    original_identity = summaries[-1]["analysis_identity"]

    assignment, = walk(builder.analysis.routines[ENTRY].execution, F.Assignment_Stmt)
    assignment.items = (*assignment.items[:2], assignment.items[0])
    builder.check_numerical_capture_origins(ENTRY)
    assert builder.native_effects(ENTRY) == original_effects
    assert source_compute.native_participation(builder.analysis, ENTRY) == "serial"
    assert len(summaries) == 6
    assert {summary["summary_role"] for summary in summaries[3:]} == {"private_projection"}
    assert all(summary["analysis_identity"] != original_identity for summary in summaries[3:])


def test_private_execution_cannot_be_adopted_as_original_generated_source(subject):
    _path, builder = subject
    assignment, = walk(builder.analysis.routines[ENTRY].execution, F.Assignment_Stmt)
    assignment.items = (*assignment.items[:2], assignment.items[0])
    assert builder.analysis.summarize(ENTRY)["summary_role"] == "private_projection"
    with pytest.raises(CompilationError, match="original source.*authority"):
        builder.numerical(ENTRY)
    assert ENTRY not in builder.generated
    assert ENTRY not in builder.numerical_ir
